#!/bin/bash
# Verify the final PKG payload after packaging. This has no installation side
# effects and is safe on a developer machine as well as a CI runner.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SOURCE_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
VERSION="$(tr -d '\r\n' < "$SOURCE_DIR/VERSION")"
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "VERSION must use MAJOR.MINOR.PATCH form, got: $VERSION" >&2
  exit 1
fi

INSTALLER_PATH="${1:-$SOURCE_DIR/build/bin/XIASS-Tools-macOS-universal-v${VERSION}-Installer.pkg}"
if [[ ! -f "$INSTALLER_PATH" || ! -s "$INSTALLER_PATH" ]]; then
  echo "Expected installer is missing or empty: $INSTALLER_PATH" >&2
  exit 1
fi

TEMP_PARENT="${TMPDIR:-/tmp}"
VERIFY_DIR="$(mktemp -d "$TEMP_PARENT/xiass-tools-pkg-verify.XXXXXX")"
cleanup() {
  # This exact directory is generated by mktemp above. Never accept a caller
  # path or delete a general temporary directory.
  case "${VERIFY_DIR:-}" in
    "$TEMP_PARENT"/xiass-tools-pkg-verify.*)
      /bin/rm -rf "$VERIFY_DIR"
      ;;
  esac
}
trap cleanup EXIT

EXPANDED_PATH="$VERIFY_DIR/expanded"
/usr/sbin/pkgutil --expand-full "$INSTALLER_PATH" "$EXPANDED_PATH"

PAYLOAD_ROOT="$EXPANDED_PATH/xiass-tools.pkg/Payload"
APPLICATIONS_ROOT="$PAYLOAD_ROOT/Applications"
PAYLOAD_APP="$APPLICATIONS_ROOT/XIASS Tools.app"
INFO_PLIST="$PAYLOAD_APP/Contents/Info.plist"
EXECUTABLE="$PAYLOAD_APP/Contents/MacOS/XIASS Tools"
if [[ ! -f "$INFO_PLIST" || ! -f "$EXECUTABLE" || ! -x "$EXECUTABLE" ]]; then
  echo "Installer payload has no complete XIASS Tools application layout." >&2
  exit 1
fi

# The release contract is a single self-contained application. Checking only
# the expected path would not detect a stale second app or another top-level
# payload copied into the component package by a contaminated build tree.
UNEXPECTED_PAYLOAD_ENTRY="$(/usr/bin/find "$PAYLOAD_ROOT" -mindepth 1 -maxdepth 1 ! -name Applications -print -quit)"
UNEXPECTED_APPLICATION_ENTRY="$(/usr/bin/find "$APPLICATIONS_ROOT" -mindepth 1 -maxdepth 1 ! -name 'XIASS Tools.app' -print -quit)"
APPLICATION_ENTRY_COUNT="$(/usr/bin/find "$APPLICATIONS_ROOT" -mindepth 1 -maxdepth 1 -print | /usr/bin/wc -l | /usr/bin/tr -d ' ')"
if [[ -n "$UNEXPECTED_PAYLOAD_ENTRY" || -n "$UNEXPECTED_APPLICATION_ENTRY" || "$APPLICATION_ENTRY_COUNT" != "1" ]]; then
  echo "Installer payload must contain exactly one XIASS Tools application and no additional top-level payload." >&2
  exit 1
fi

if [[ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$INFO_PLIST")" != "com.xiass.tools" ]]; then
  echo "Installer payload bundle identifier is incorrect." >&2
  exit 1
fi
if [[ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$INFO_PLIST")" != "$VERSION" ]]; then
  echo "Installer payload short version is incorrect." >&2
  exit 1
fi
if [[ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleVersion' "$INFO_PLIST")" != "$VERSION" ]]; then
  echo "Installer payload build version is incorrect." >&2
  exit 1
fi
if [[ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleExecutable' "$INFO_PLIST")" != "XIASS Tools" ]]; then
  echo "Installer payload executable metadata is incorrect." >&2
  exit 1
fi

ARCHITECTURES="$(/usr/bin/lipo -archs "$EXECUTABLE")"
if [[ " $ARCHITECTURES " != *" arm64 "* || " $ARCHITECTURES " != *" x86_64 "* ]]; then
  echo "Installer payload is not universal: $ARCHITECTURES" >&2
  exit 1
fi
/usr/bin/codesign --verify --deep --strict "$PAYLOAD_APP"

EXECUTABLE_COUNT="$(/usr/bin/find "$PAYLOAD_APP/Contents/MacOS" -maxdepth 1 -type f | /usr/bin/wc -l | /usr/bin/tr -d ' ')"
if [[ "$EXECUTABLE_COUNT" != "1" ]]; then
  echo "Installer payload contains an unexpected executable layout." >&2
  exit 1
fi

echo "macOS installer payload verification passed."
